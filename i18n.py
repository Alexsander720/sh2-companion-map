def language(value: str | None) -> str:
    return 'ru' if str(value or '').lower().startswith('ru') else 'en'


def t(key: str, lang: str = 'en') -> str:
    return STRINGS[language(lang)].get(key, key)


def category(key: str, lang: str = 'en') -> str:
    value = CATEGORIES.get(key)
    return value[language(lang) == 'ru'] if value else t('poi', lang)


def puzzle_title(cls_id: str, lang: str = 'en') -> str:
    value = PUZZLE_NAMES.get(cls_id)
    if value:
        return value[language(lang) == 'ru']
    return cls_id.replace('_', ' ')
